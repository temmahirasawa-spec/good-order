-- ────────────────────────────────────────────────────────────
-- SECTION 1: テーブル作成
-- ────────────────────────────────────────────────────────────

-- stores（店舗）
CREATE TABLE IF NOT EXISTS public.stores (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  name        text        NOT NULL,
  slug        text        NOT NULL UNIQUE,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- categories（カテゴリー）
-- ※ spec外だが URL ルーティングに必要なため slug 列を追加
CREATE TABLE IF NOT EXISTS public.categories (
  id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id      uuid        NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  slug          text        NOT NULL,                -- URL識別子 例: "pancake"
  name          text        NOT NULL,                -- 表示名 例: "パンケーキ"
  caption       text,                                -- 英語サブテキスト 例: "Pancake"
  image_url     text,
  display_order integer     NOT NULL DEFAULT 0,
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (store_id, slug)
);

-- menu_items（メニュー）
-- ※ spec外だが UI に必要なため tag 列を追加
CREATE TABLE IF NOT EXISTS public.menu_items (
  id               uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id         uuid        NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  category_id      uuid        NOT NULL REFERENCES public.categories(id) ON DELETE CASCADE,
  name             text        NOT NULL,
  description      text,
  price            integer     NOT NULL,             -- 税抜き円
  image_url        text,
  tag              text,                             -- "人気" | "おすすめ" | "限定" | NULL
  calories         integer,                          -- kcal
  serving_time_min integer,                          -- 提供目安（分）
  is_available     boolean     NOT NULL DEFAULT true,
  display_order    integer     NOT NULL DEFAULT 0,
  created_at       timestamptz NOT NULL DEFAULT now()
);

-- orders（注文）
CREATE TABLE IF NOT EXISTS public.orders (
  id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id     uuid        NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  table_number integer     NOT NULL,
  status       text        NOT NULL DEFAULT 'pending'
                           CHECK (status IN ('pending', 'preparing', 'served')),
  total_amount integer     NOT NULL DEFAULT 0,       -- 税込み円
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- order_items（注文明細）
CREATE TABLE IF NOT EXISTS public.order_items (
  id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id     uuid        NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  menu_item_id uuid        NOT NULL REFERENCES public.menu_items(id),
  quantity     integer     NOT NULL DEFAULT 1,
  unit_price   integer     NOT NULL,                 -- 注文時点の単価（税抜き）
  created_at   timestamptz NOT NULL DEFAULT now()
);


-- ────────────────────────────────────────────────────────────
-- SECTION 2: インデックス
-- ────────────────────────────────────────────────────────────

CREATE INDEX IF NOT EXISTS idx_categories_store
  ON public.categories (store_id, display_order);

CREATE INDEX IF NOT EXISTS idx_menu_items_category
  ON public.menu_items (category_id, display_order);

CREATE INDEX IF NOT EXISTS idx_menu_items_store_available
  ON public.menu_items (store_id, is_available);

CREATE INDEX IF NOT EXISTS idx_orders_store_status
  ON public.orders (store_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_order_items_order
  ON public.order_items (order_id);


-- ────────────────────────────────────────────────────────────
-- SECTION 3: Storage バケット
-- ────────────────────────────────────────────────────────────

INSERT INTO storage.buckets (id, name, public)
VALUES ('menu-images', 'menu-images', true)
ON CONFLICT (id) DO NOTHING;

-- Storage RLS: 全員が画像を閲覧可能
CREATE POLICY "menu_images_select_all"
  ON storage.objects FOR SELECT
  USING (bucket_id = 'menu-images');

-- Storage RLS: 認証済みユーザーのみアップロード・削除可能
CREATE POLICY "menu_images_write_authenticated"
  ON storage.objects FOR INSERT
  TO authenticated
  WITH CHECK (bucket_id = 'menu-images');

CREATE POLICY "menu_images_delete_authenticated"
  ON storage.objects FOR DELETE
  TO authenticated
  USING (bucket_id = 'menu-images');


